// SQL is reviewed in sql/, then embedded for Deno's standalone compiler.
import { DatabaseSync } from "node:sqlite";

const schema = await Deno.readTextFile("sql/migrations/001_initial.sql");
const source = await Deno.readTextFile("sql/queries.sql");
const queries = Object.fromEntries([...source.matchAll(/-- name: (\w+)\n([\s\S]*?)(?=-- name:|$)/g)]
  .map((match) => [match[1]!, match[2]!.trim()]));
const db = new DatabaseSync(":memory:");
try {
  db.exec(schema);
  for (const sql of Object.values(queries)) db.prepare(sql);
  const objects = (type: string) =>
    db.prepare(
      "SELECT name FROM sqlite_master WHERE type=? AND name NOT LIKE 'sqlite_%' ORDER BY name",
    ).all(type).map((row) => row.name);
  const checksum = Array.from(
    new Uint8Array(await crypto.subtle.digest("SHA-256", new TextEncoder().encode(schema))),
    (b) => b.toString(16).padStart(2, "0"),
  ).join("");
  const output = `// Generated by deno task db:generate. Edit sql/ instead.\n` +
    `export const CANONICAL_SCHEMA = [${JSON.stringify(schema)}] as const;\n` +
    `export const MIGRATIONS = [{version:1,name:"ts_initial",checksum:${
      JSON.stringify(checksum)
    }}] as const;\n` +
    ["table", "index", "trigger"].map((type) =>
      `export const REQUIRED_${type === "index" ? "INDEXES" : type.toUpperCase() + "S"} = ${
        JSON.stringify(objects(type))
      } as const;\n`
    ).join("");
  const generated = new Map([
    ["src/db/schema.ts", output],
    [
      "src/db/queries.ts",
      `// Generated by deno task db:generate. Edit sql/queries.sql instead.\nexport const SQL = ${
        JSON.stringify(queries, null, 2)
      } as const;\n`,
    ],
  ]);
  for (const [path, text] of generated) {
    const formatted = await new Deno.Command(Deno.execPath(), {
      args: ["fmt", "-", "--ext=ts"],
      stdin: "piped",
      stdout: "piped",
      stderr: "null",
    }).spawn();
    const writer = formatted.stdin.getWriter();
    await writer.write(new TextEncoder().encode(text));
    await writer.close();
    const result = await formatted.output();
    if (!result.success) throw new Error("format generated SQL failed");
    const value = new TextDecoder().decode(result.stdout);
    if (Deno.args.includes("--check")) {
      if (await Deno.readTextFile(path) !== value) {
        throw new Error(`generated SQL is stale: ${path}`);
      }
    } else await Deno.writeTextFile(path, value);
  }
} finally {
  db.close();
}
